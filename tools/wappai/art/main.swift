import AppKit
import SceneKit
import Metal
import simd
let output=CommandLine.arguments[1]
try FileManager.default.createDirectory(atPath:output,withIntermediateDirectories:true)
func geometry(_ m:PipMesh)->SCNGeometry {
    let vertices=m.vertices.map{SCNVector3($0.x,$0.y,$0.z)},normals=m.normals.map{SCNVector3($0.x,$0.y,$0.z)}
    return SCNGeometry(sources:[SCNGeometrySource(vertices:vertices),SCNGeometrySource(normals:normals)],elements:[SCNGeometryElement(indices:m.triangles,primitiveType:.triangles)])
}
var header="#pragma once\n// Generated by tools/wappai/art from PipSculpt.swift. RGB565 + alpha.\n#include <stdint.h>\nstruct PipRaster {int16_t x,y,w,h;const uint32_t *pixels;};\n"
var rasters:[String]=[]
for rig in 0...2 {
    for pass in ["full","body","leftArm","rightArm","leftFoot","rightFoot"] {
        let scene=SCNScene()
        scene.background.contents=NSColor.clear
        for part in PipSculpt.parts(rig:rig,face:pass=="full") {
            let limb=["leftArm","rightArm","leftFoot","rightFoot"].contains(part.name)
            if pass=="body" && limb {continue}
            if pass != "full" && pass != "body" && part.name != pass {continue}
            let node=SCNNode(geometry:geometry(part.mesh)),mat=SCNMaterial()
            mat.diffuse.contents=NSColor(red:CGFloat((part.color>>16)&255)/255,green:CGFloat((part.color>>8)&255)/255,blue:CGFloat(part.color&255)/255,alpha:1)
            mat.lightingModel = .physicallyBased;mat.roughness.contents=part.roughness;mat.metalness.contents=0
            node.geometry?.materials=[mat];node.position=SCNVector3(part.position.x,part.position.y,part.position.z);node.eulerAngles.z=CGFloat(part.rotation)
            scene.rootNode.addChildNode(node)
        }
        let camera=SCNNode();camera.camera=SCNCamera();camera.camera!.usesOrthographicProjection=true;camera.camera!.orthographicScale=1.65;camera.camera!.zNear=0.1;camera.camera!.zFar=100
        camera.position=SCNVector3(0,0.27,7);scene.rootNode.addChildNode(camera)
        camera.camera!.wantsHDR=true;camera.camera!.exposureOffset=0;camera.camera!.minimumExposure=0;camera.camera!.maximumExposure=0
        for (xyz,intensity) in [(SCNVector3(-3,5,5),CGFloat(850)),(SCNVector3(4,1,3),CGFloat(350)),(SCNVector3(-1,2,-3),CGFloat(600))] {
            let n=SCNNode();n.light=SCNLight();n.light!.type = .directional;n.light!.intensity=intensity;n.position=xyz;n.look(at:SCNVector3(0,0,0));scene.rootNode.addChildNode(n)
        }
        let ambient=SCNNode();ambient.light=SCNLight();ambient.light!.type = .ambient;ambient.light!.intensity=350;scene.rootNode.addChildNode(ambient)
        let renderer=SCNRenderer(device:MTLCreateSystemDefaultDevice(),options:nil);renderer.scene=scene;renderer.pointOfView=camera
        let image=renderer.snapshot(atTime:0,with:CGSize(width:512,height:512),antialiasingMode:.multisampling4X)
        let data=NSBitmapImageRep(data:image.tiffRepresentation!)!.representation(using:.png,properties:[:])!
        try data.write(to:URL(fileURLWithPath:"\(output)/\(rig)-\(pass).png"))
        if pass != "full" {
            let baked=renderer.snapshot(atTime:0,with:CGSize(width:256,height:256),antialiasingMode:.multisampling4X)
            let rep=NSBitmapImageRep(data:baked.tiffRepresentation!)!
            var x0=256,y0=256,x1=0,y1=0
            for y in 0..<256 {for x in 0..<256 {if (rep.colorAt(x:x,y:y)?.alphaComponent ?? 0)>0.01 {x0=min(x0,x);y0=min(y0,y);x1=max(x1,x);y1=max(y1,y)}}}
            let id="pip_\(rig)_\(pass)"
            header += "static const uint32_t \(id)[] = {\n"
            for y in y0...y1 {for x in x0...x1 {
                let c=rep.colorAt(x:x,y:y)!.usingColorSpace(.deviceRGB)!
                let bayer=[0,8,2,10,12,4,14,6,3,11,1,9,15,7,13,5]
                let noise=CGFloat(bayer[(y%4)*4+x%4])/16-0.5
                let r=UInt32(max(0,min(31,(c.redComponent*31+noise).rounded())))
                let g=UInt32(max(0,min(63,(c.greenComponent*63+noise).rounded())))
                let b=UInt32(max(0,min(31,(c.blueComponent*31+noise).rounded()))),a=UInt32(c.alphaComponent*255)
                let v=(r<<11)|(g<<5)|b|(a<<16)
                header += String(format:"0x%06x,",v)
            };header += "\n"}
            header += "};\n"
            rasters.append("{\(x0),\(y0),\(x1-x0+1),\(y1-y0+1),\(id)}")
        }
    }
}

header += "static const PipRaster PIP_ART[3][5] = {\n"
for rig in 0...2 {header += "{"+rasters[(rig*5)..<(rig*5+5)].joined(separator:",")+"},\n"}
header += "};\n"
try header.write(toFile:output+"/pip_art.gen.h",atomically:true,encoding:.utf8)
