#!/usr/bin/env python3
"""character/creature.json -> firmware/src/face/emotions.gen.h + server/sim/emotions.json

Resolves defaults, 'extends', per-side overrides and enum names, so the firmware and the web
simulator consume exactly the same numbers.

    python3 tools/gen_face.py
"""
import copy
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "character" / "creature.json"
OUT_H = ROOT / "firmware" / "src" / "face" / "emotions.gen.h"
OUT_JSON = ROOT / "server" / "sim" / "emotions.json"

EYE_SHAPES = ["round", "arc_up", "arc_down", "heart", "star", "spiral", "x", "squint", "line"]
MOUTH_SHAPES = ["curve", "o", "wave", "cat", "none"]
ANIMS = ["none", "sway", "bounce", "tremble", "float", "wobble", "lean"]
FX = ["hearts", "tears", "sweat", "zzz", "sparkles", "question", "exclaim", "anger", "notes", "steam", "dots", "blush"]

EYE_KEYS = ["dx", "y", "w", "h", "r", "rot", "lidT", "lidTA", "lidB", "hl", "shape"]
BROW_KEYS = ["a", "y", "dx", "w", "th", "ang", "curve"]
MOUTH_KEYS = ["dx", "y", "w", "curve", "open", "th", "rot", "shape"]


def hex_rgb(h):
    h = h.lstrip("#")
    return [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]


def resolve(data, name, seen=()):
    if name in seen:
        raise SystemExit(f"extends loop at {name}")
    e = data["emotions"][name]
    d = data["defaults"]
    if "extends" in e:
        base = resolve(data, e["extends"], seen + (name,))
    else:
        base = {
            "eyeL": dict(d["eye"]), "eyeR": dict(d["eye"]),
            "browL": dict(d["brow"]), "browR": dict(d["brow"]),
            "mouth": dict(d["mouth"]), "face": copy.deepcopy(d["face"]),
            "color": data.get("color", "#62F2DF"),
        }
    r = copy.deepcopy(base)
    for side in ("L", "R"):
        r["eye" + side].update(e.get("eye", {}))
        r["eye" + side].update(e.get("eye" + side, {}))
        r["brow" + side].update(e.get("brow", {}))
        r["brow" + side].update(e.get("brow" + side, {}))
    r["mouth"].update(e.get("mouth", {}))
    r["face"].update(e.get("face", {}))
    if "color" in e:
        r["color"] = e["color"]
    return r


def to_floats(r):
    v = []
    for side in ("L", "R"):
        eye = r["eye" + side]
        for k in EYE_KEYS:
            v.append(EYE_SHAPES.index(eye[k]) if k == "shape" else float(eye[k]))
    for side in ("L", "R"):
        b = r["brow" + side]
        v += [float(b[k]) for k in BROW_KEYS]
    m = r["mouth"]
    for k in MOUTH_KEYS:
        v.append(MOUTH_SHAPES.index(m[k]) if k == "shape" else float(m[k]))
    f = r["face"]
    v.append(float(f["cheek"]))
    v += [float(f["dy"]), float(f["scale"]), float(f["rot"])]
    v += hex_rgb(r["color"])
    v.append(float(f["glow"]))
    v.append(ANIMS.index(f["anim"]))
    v.append(float(f["animAmp"]))
    mask = 0
    for fx in f["fx"]:
        mask |= 1 << FX.index(fx)
    v.append(mask)
    return v


def fmt(x):
    if not isinstance(x, float):
        return str(x)
    t = f"{x:.6g}"
    if "." not in t and "e" not in t:
        t += ".0"
    return t + "f"


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    names = list(data["emotions"].keys())
    assert names[0] == "idle", "first emotion must be idle"
    rows, resolved = [], {}
    for n in names:
        r = resolve(data, n)
        resolved[n] = r
        vals = ", ".join(fmt(x) for x in to_floats(r))
        rows.append(f'    {{"{n}", {{{vals}}}}},')
    OUT_H.write_text(
        "// GENERATED by tools/gen_face.py from character/creature.json - do not edit\n#pragma once\n"
        '#include "face.h"\n'
        f"static const int N_EMOTIONS = {len(names)};\n"
        "static const Emotion EMOTIONS[] = {\n" + "\n".join(rows) + "\n};\n",
        encoding="utf-8")
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps({"name": data.get("name"), "eyeShapes": EYE_SHAPES, "mouthShapes": MOUTH_SHAPES,
                                    "anims": ANIMS, "fx": FX, "emotions": resolved}, ensure_ascii=False, indent=1),
                        encoding="utf-8")
    print(f"{len(names)} emotions -> {OUT_H.relative_to(ROOT)}, {OUT_JSON.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
